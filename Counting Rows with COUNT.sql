/* ------------------------------------------------------------
Counting Rows with COUNT
------------------------------------------------------------ */
-- ============================================================
-- STEP 1: Count All Rows
-- ============================================================
USE SweetShop;
GO

SELECT COUNT(*)
FROM Inventory.Sweets;
GO

-- ============================================================
-- STEP 2: Count with an Alias
-- ============================================================
SELECT COUNT(*) AS TotalSweets
FROM Inventory.Sweets;
GO

-- ============================================================
-- STEP 3: Count Rows Matching a Condition
-- ============================================================
SELECT COUNT(*) AS LowStockItems
FROM Inventory.Sweets
WHERE Quantity < 40;
GO

