/* ------------------------------------------------------------
Retrieving All Data with SELECT
 ------------------------------------------------------------ */
 USE SweetShop;
 GO

 -- ============================================================
-- STEP 1: Retrieve All Rows and Columns
-- ============================================================
SELECT *
FROM Inventory.Sweets;
GO

-- ============================================================
-- STEP 2: Retrieve Specific Columns
-- ============================================================
SELECT SweetId,SweetName
FROM Inventory.Sweets;
GO

-- ============================================================
-- STEP 3: Retrieve a Single Column
-- ============================================================
SELECT SweetName
FROM Inventory.Sweets;
GO

